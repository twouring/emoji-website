/* 品項說明日文（以中文品名為鍵），分檔放 lib/menu-ja-notes/*.json */
const NOTE_JA = {};
(function () {
  const fs = require('fs'), path = require('path'), dir = path.join(__dirname, 'menu-ja-notes');
  fs.readdirSync(dir).filter(f => f.endsWith('.json')).sort().forEach(f => Object.assign(NOTE_JA, JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8'))));
})();
const noteJaOf = zh => NOTE_JA[zh] || '';
function fillMenuJa(items) {
  let n = 0;
  (items || []).forEach(it => {
    if (!it) return;
    if (!it.ja && MENU_JA[it.zh]) { it.ja = MENU_JA[it.zh]; n++; }
    if (!it.note_ja && it.note && NOTE_JA[it.zh]) { it.note_ja = NOTE_JA[it.zh]; n++; }
  });
  return n;
}
module.exports = { MENU_JA, NOTE_JA, noteJaOf, fillMenuJa };
